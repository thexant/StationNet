import assert from 'node:assert/strict';
import { blankAgenda, occurrenceStarts, occurrences, onDay, searchable } from '../stationnet/office_agenda/model.js';

const multiDay = { id: 'e1', title: 'Conference', startDate: '2026-10-29', endDate: '2026-11-02', allDay: true, showOnMonth: true, repeat: { frequency: 'none' } };
const hidden = { id: 'e2', title: 'Short note', startDate: '2026-10-30', endDate: '2026-10-30', allDay: false, startTime: '14:00', showOnMonth: false, repeat: { frequency: 'none' } };
const weekly = { id: 'e3', title: 'Team', startDate: '2026-10-28', endDate: '2026-10-28', repeat: { frequency: 'weekly', interval: 2, weekdays: [1, 3] } };
assert.deepEqual(occurrenceStarts(weekly, '2026-10-26', '2026-11-16'), ['2026-10-28', '2026-11-09', '2026-11-11']);
assert.deepEqual(occurrenceStarts({ startDate: '2024-02-29', repeat: { frequency: 'yearly', interval: 1 } }, '2025-01-01', '2028-12-31'), ['2028-02-29']);
assert.deepEqual(occurrenceStarts({ startDate: '2026-01-31', repeat: { frequency: 'monthly', interval: 1 } }, '2026-02-01', '2026-04-30'), ['2026-03-31']);
assert.deepEqual(occurrenceStarts({ startDate: '9999-12-31', repeat: { frequency: 'daily', interval: 1 } }, '9999-12-31', '9999-12-31'), ['9999-12-31']);
const data = blankAgenda();
data.events.push(multiDay, hidden);
data.contacts.push({ id: 'c1', name: 'Ada', birthday: '1990-10-30', anniversary: '2010-11-03', notes: 'Friend' });
data.tasks.push({ id: 't1', title: 'Prepare slides', dueDate: '2026-10-30', notes: 'For conference', subtasks: [{ title: 'Outline' }] });
data.tasks.push({ id: 't2', title: 'Private checklist', dueDate: '2026-10-30', showOnCalendar: false });
const items = occurrences(data, '2026-10-30', '2026-10-31');
assert.ok(items.some(item => item.id === 'e1' && onDay(item, '2026-10-31')));
assert.ok(items.some(item => item.id === 'e2' && item.onMonth === false));
assert.ok(items.some(item => item.id === 'c1' && item.title.includes('Birthday')));
assert.ok(items.some(item => item.id === 't1' && item.kind === 'task'));
assert.ok(!items.some(item => item.id === 't2'));
assert.ok(occurrences(data, '2026-10-30', '2026-10-31', { includeHiddenTasks: true }).some(item => item.id === 't2'));
assert.deepEqual(searchable(data, 'private checklist').map(item => item.kind), ['task']);
assert.deepEqual(searchable(data, 'outline').map(item => item.kind), ['task']);
assert.deepEqual(searchable(data, 'friend').map(item => item.kind), ['contact']);
